/**
 * Generates src/evaluator/unicode-data.generated.ts — the Unicode block and
 * script tables behind the Font namespace and the glyph `script` / `block`
 * properties (docs/fonts.md).
 *
 * Inputs (vendored, Unicode 16.0.0, under the Unicode terms of use):
 *   scripts/unicode/Blocks-16.0.0.txt       — block names and ranges
 *   scripts/unicode/ScriptNames-16.0.0.txt  — the `sc` lines of PropertyValueAliases.txt
 *
 * Script ranges come from the JS engine's own Unicode data (`\p{Script=…}`),
 * which must be the same Unicode version — the script checks and refuses to
 * run otherwise, so the two tables can't disagree.
 *
 *   npx tsx scripts/generate-unicode-data.ts
 */

import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';

import { Command } from 'commander';

const UNICODE_VERSION = '16.0.0';
const ROOT = fileURLToPath(new URL('..', import.meta.url));
const OUT = join(ROOT, 'src/evaluator/unicode-data.generated.ts');

function generate(): void {
  if (!UNICODE_VERSION.startsWith(process.versions.unicode ?? '')) {
    throw new Error(
      `Node's Unicode is ${process.versions.unicode}; the vendored tables are ${UNICODE_VERSION}. ` +
        'Update scripts/unicode/ to the matching version (or use a matching Node).',
    );
  }

  // ── Blocks ──────────────────────────────────────────────────────────────
  const blocks: [number, number, string][] = [];
  for (const line of readFileSync(join(ROOT, `scripts/unicode/Blocks-${UNICODE_VERSION}.txt`), 'utf8').split('\n')) {
    const m = /^([0-9A-F]+)\.\.([0-9A-F]+);\s*(.+?)\s*$/.exec(line);
    if (m) blocks.push([parseInt(m[1], 16), parseInt(m[2], 16), m[3]]);
  }

  // ── Scripts ─────────────────────────────────────────────────────────────
  const scriptLongNames: string[] = [];
  for (const line of readFileSync(join(ROOT, `scripts/unicode/ScriptNames-${UNICODE_VERSION}.txt`), 'utf8').split(
    '\n',
  )) {
    const m = /^sc\s*;\s*\w+\s*;\s*(\w+)/.exec(line);
    if (m) scriptLongNames.push(m[1]);
  }
  const usable = scriptLongNames.filter((name) => {
    try {
      return new RegExp(`\\p{Script=${name}}`, 'u').unicode; // throws for names the engine lacks
    } catch {
      console.warn(`skipping script the JS engine doesn't know: ${name}`);
      return false;
    }
  });
  const tests = usable.map((name) => new RegExp(`^\\p{Script=${name}}$`, 'u'));
  const unknownIndex = usable.indexOf('Unknown');
  if (unknownIndex < 0) throw new Error('Script list lacks Unknown');

  // Walk every code point; most runs share a script, so try the last one first.
  const ranges: number[] = [];
  let runStart = 0;
  let runScript = -1;
  let last = unknownIndex;
  for (let cp = 0; cp <= 0x10ffff; cp++) {
    const ch = String.fromCodePoint(cp);
    let idx = -1;
    if (tests[last].test(ch)) idx = last;
    else {
      for (let i = 0; i < tests.length; i++) {
        if (tests[i].test(ch)) {
          idx = i;
          break;
        }
      }
    }
    if (idx < 0) idx = unknownIndex; // surrogates and the like
    last = idx;
    if (idx !== runScript) {
      if (runScript >= 0 && runScript !== unknownIndex) ranges.push(runStart, cp - 1, runScript);
      runStart = cp;
      runScript = idx;
    }
  }
  if (runScript !== unknownIndex) ranges.push(runStart, 0x10ffff, runScript);

  const displayNames = usable.map((n) => n.replace(/_/g, ' '));

  const out = `// GENERATED by scripts/generate-unicode-data.ts — do not edit.
  // Unicode ${UNICODE_VERSION}: blocks from Blocks.txt, scripts from the JS engine's
  // \\p{Script=…} data. ${blocks.length} blocks, ${ranges.length / 3} script ranges.

  export const UNICODE_VERSION = '${UNICODE_VERSION}';

  /** [start, end, name] for every Unicode block, in code-point order. */
  export const BLOCKS: readonly (readonly [number, number, string])[] = ${JSON.stringify(blocks)};

  /** Script names (Unicode long names, underscores as spaces). Index = script id. */
  export const SCRIPT_NAMES: readonly string[] = ${JSON.stringify(displayNames)};

  /**
   * Flattened [start, end, scriptId] triples in code-point order. Code points
   * not covered are script "Unknown" (unassigned, surrogates, private use).
   */
  export const SCRIPT_RANGES: readonly number[] = ${JSON.stringify(ranges)};
  `;
  writeFileSync(OUT, out);
  console.log(`wrote ${OUT}: ${blocks.length} blocks, ${usable.length} scripts, ${ranges.length / 3} ranges`);
}

new Command()
  .name('generate-unicode-data')
  .description('Generate src/evaluator/unicode-data.generated.ts (Unicode blocks + scripts) for the Font namespace')
  .action(() => generate())
  .parse();
